// Current language, remembered in the browser
let currentLang = localStorage.getItem("lang") || "en";

/** Returns the translation for `key` in the current language (falls back to English, then the key). */
function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || key;
}

/** Fills every element that has data-i18n / data-i18n-placeholder with the current language. */
function applyStaticTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}

/** Switches language, flips text direction for Urdu/Sindhi (RTL), and asks app.js to redraw. */
function setLang(lang) {
  currentLang = lang;
  localStorage.setItem("lang", lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "en" ? "ltr" : "rtl";
  const sel = document.getElementById("lang-select");
  if (sel) sel.value = lang;
  applyStaticTranslations();
  if (typeof onLanguageChange === "function") onLanguageChange();
}